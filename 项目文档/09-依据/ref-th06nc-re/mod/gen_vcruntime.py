#!/usr/bin/env python3
"""
gen_vcruntime.py -- regenerate the vcruntime140 proxy's export plumbing.

Input:  exports.txt   (one exported function name per line, taken from the
                       real vcruntime140.dll; 74 names on VC++ 14.4x / Wine)
Output: vcruntime_thunks.S     one thunk per export, each in .text, plus a
                               pointer slot in .data
        vcruntime140_full.def  .def mapping export name -> thunk symbol
        vcruntime_syms.h       extern declarations + {name, &slot} table

CRITICAL: every thunk is emitted after an explicit `.text` directive.
Emitting `.text` only once puts all but the first thunk into `.data`, and
calling them faults with a DEP violation (observed as "MSVCP140.dll failed to
initialize" under Wine).
"""

import re
import sys


def sanitize(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def main() -> int:
    try:
        names = [l.strip() for l in open("exports.txt") if l.strip()]
    except FileNotFoundError:
        print("exports.txt not found (run from mod/)", file=sys.stderr)
        return 1

    asm = []
    defs = ["LIBRARY vcruntime140", "EXPORTS"]
    syms = ["/* generated by gen_vcruntime.py -- do not edit */"]

    for n in names:
        syms.append(f"extern void *rp_{sanitize(n)};")
    syms.append("static const struct { const char *name; void **slot; } g_syms[] = {")

    for n in names:
        s = sanitize(n)
        asm += [
            "\t.text",                       # <- must precede every thunk
            f"\t.globl t_{s}",
            f"t_{s}:",
            f"\tjmp *rp_{s}(%rip)",
            "",
            "\t.data",
            f"\t.globl rp_{s}",
            f"rp_{s}:",
            "\t.quad 0",
            "",
        ]
        defs.append(f"    {n}=t_{s}")
        syms.append(f'    {{ "{n}", (void **)&rp_{s} }},')

    syms.append("};")

    open("vcruntime_thunks.S", "w").write("\n".join(asm) + "\n")
    open("vcruntime140_full.def", "w").write("\n".join(defs) + "\n")
    open("vcruntime_syms.h", "w").write("\n".join(syms) + "\n")

    print(f"generated {len(names)} thunks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
